import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

/** Generate the Node-test fallback for Vite's import.meta.glob module map. */
export function syncModManifestIndex(root = process.cwd()) {
  const modsDir = path.join(root, 'src', 'mods')
  const entries = readdirSync(modsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^mod-[a-z0-9-]+$/.test(entry.name))
    .filter((entry) => existsSync(path.join(modsDir, entry.name, 'manifest.ts')))
    .sort((a, b) => a.name.localeCompare(b.name))

  const imports = entries.map(
    (entry, index) => `import mod${index} from './${entry.name}/manifest'`,
  )
  const values = entries.map((_, index) => `  mod${index},`)
  const source = [
    '/* AUTO-GENERATED by scripts/lib/mod-index.mjs. Do not edit manually. */',
    ...imports,
    '',
    'export const STATIC_MOD_MANIFESTS = [',
    ...values,
    ']',
    '',
  ].join('\n')

  const output = path.join(modsDir, 'manifest-index.ts')
  writeFileSync(output, source, { encoding: 'utf8' })
  return { count: entries.length, output }
}
